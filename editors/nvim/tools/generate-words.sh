#!/bin/sh
#
# Regenerate syntax/bund_words.vim from what bund2 registers.
#
#   tools/generate-words.sh            uses the bund2 on PATH
#   BUND2=/path/to/bund2 tools/generate-words.sh
#
# Every name `bund2 words` prints becomes a bundBuiltin keyword. Names with a
# character outside ASCII cannot be keywords, so they become matches bounded
# by whitespace, as the grammar bounds a name. `:` and `;` are left out: they
# are commands, and syntax/bund.vim matches them itself.
set -eu

here=$(cd "$(dirname "$0")/.." && pwd)
bund2=${BUND2:-bund2}
out="$here/syntax/bund_words.vim"

if ! command -v "$bund2" >/dev/null 2>&1; then
  echo "generate-words: cannot run '$bund2'; set BUND2 to the binary" >&2
  exit 1
fi

version=$("$bund2" --version 2>/dev/null | head -n 1 || true)
tmp="$out.tmp"

"$bund2" words | LC_ALL=C sort -u | LC_ALL=C awk -v version="$version" '
function flush() { if (line != "") { print "syn keyword bundBuiltin" line; line = "" } }
BEGIN {
  print "\" Vim syntax: every word bund2 registers."
  print "\" Generated by tools/generate-words.sh from `bund2 words`. Do not edit."
  if (version != "") print "\" " version
  print ""
}
/^[[:space:]]*$/ { next }
/^[:;]+$/        { next }
/[\200-\377]/    { wide[++n] = $0; next }
{
  w = $0
  gsub(/\|/, "\\|", w)
  if (length(line) + length(w) + 1 > 70) flush()
  line = line " " w
}
END {
  flush()
  if (n > 0) print ""
  for (i = 1; i <= n; i++)
    printf "syn match bundBuiltin '\''\\%%(^\\|[[:space:]\\[{(]\\)\\@1<=\\V%s\\m\\ze\\%%(\\s\\|$\\)'\''\n", wide[i]
}' > "$tmp"

mv "$tmp" "$out"
echo "wrote $out ($(grep -c '' "$out") lines)"
